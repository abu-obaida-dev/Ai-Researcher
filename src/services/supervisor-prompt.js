/** الترحيب: أول رسالة في تاريخه فقط، وإلا بداية مباشرة بلا ترحيب. */
function welcomeSection(c) {
  if (!c.isFirstMessageEver) {
    return [
      '# البداية (ليست أول رسالة)',
      'لا ترحيب إطلاقاً. ابدئي بالمحتوى مباشرة.',
      c.openTask && c.daysSinceLast >= 3
        ? `وإن كانت «أيام منذ آخر نشاط» كبيرة وثمة «مهمة متفق عليها» فافتتحي بالمتابعة، مثل: «اتفقنا أن ${c.openTask}، إلى أين وصلت؟».`
        : ''
    ];
  }

  const hasProfile = [c.degree, c.field, c.researchGoal, c.progressLevel].some(
    (value) => value && value !== 'غير محدد'
  );
  const hint = GOAL_OPENING_HINTS[c.researchGoalKey] || '';

  return [
    '# الترحيب والبداية (أول رسالة في تاريخه)',
    'رحّبي به ترحيباً قصيراً باسمه مرة واحدة فقط، ثم:',
    hasProfile
      ? '- أوضحي في جملتين موجزتين أنكِ تعرفين وضعه الحالي من ملفه: درجته الأكاديمية وتخصصه وهدفه من إنجاز البحث وما أنجزه حتى الآن — بصياغتك الموجزة لا بنسخ أسئلة الملف.'
      : '- إن كان ملفه فارغاً فاسأليه سؤالاً واحداً يكمل به أساسياته (درجته وتخصصه وهدفه).',
    '- ثم قدّمي أول خطوة عملية تناسب هدفه وحالته الحالية، واختمي الرد بسؤال واحد محدّداً يفتح هذه الخطوة أمامه ويُجيب عنه الباحث فوراً.',
    hint
      ? `- نقطة الانطلاق المناسبة لهدفه («${c.researchGoal}»): ${hint}. اذكري الخطوة ثم اسألي عنه سؤالاً واحداً.`
      : '- اختاري أول خطوة منطقية من مساره الحالية واسألي عن سؤال واحد يبدأ بها.',
    '- مثال على السلوك لا على النص: «مرحباً بك. بما أنك [درجته] في [تخصصه]، وهدفك [هدفه] وما زلت [حالته]، سنبدأ بـ [خطوة مناسبة]: [سؤال واحد]؟».',
    ...(hasProfile
      ? ['- لا تسأليه عن بيانات موجودة في ملفه أصلاً (درجته، تخصصه، هدفه)، ولا تذكّريه بها أكثر من مرة واحدة.']
      : []),
    '- لا تقترحي له موضوعاً أو عنواناً جاهزاً أبداً؛ هو من يختار وأنتِ تحدّدين نقطة الانطلاق فقط.',
    '- سؤال واحد في الرد كله: لا تجعليه يجيب عن أكثر من سؤال.',
    'لا تكرري هذا الترحيب في أي رسالة لاحقة.'
  ];
}

